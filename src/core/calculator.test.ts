import { describe, expect, it } from 'vitest'
import { evalExpr } from './index'

// Тесты идут только через публичный интерфейс ядра: evalExpr и EvalResult.
// Деньги — целые минорные единицы; результат выражения в основных единицах
// округляется до минорной на выходе (half away from zero).

describe('evalExpr — арифметика, приоритет, скобки', () => {
  it.each([
    ['1500/4+200', 57500],
    ['2+3*4', 1400],
    ['(2+3)*4', 2000],
    ['((1+1)*(2+2))/4', 200],
    ['5', 500],
  ])('%s → %i минорных', (input, minor) => {
    expect(evalExpr(input)).toEqual({ ok: true, minor })
  })
})

describe('evalExpr — разделитель дробной части: точка и запятая равнозначны', () => {
  it.each([
    ['1,5', 150],
    ['1.5', 150],
    ['1,5+1.5', 300],
  ])('%s → %i минорных', (input, minor) => {
    expect(evalExpr(input)).toEqual({ ok: true, minor })
  })
})

describe('evalExpr — унарный минус', () => {
  it.each([
    ['-5', -500],
    ['2*-3', -600],
    ['-(1+2)', -300],
    ['--5', 500],
  ])('%s → %i минорных', (input, minor) => {
    expect(evalExpr(input)).toEqual({ ok: true, minor })
  })
})

describe('evalExpr — точная рациональная арифметика и округление до минорной', () => {
  it.each([
    ['(1/3)*3', 100], // ровно 100: 1/3 хранится точно, а не как float
    ['100/3', 3333], // 3333,(3) → вниз
    ['1/3', 33],
    ['0.004', 0], // 0.4 минорной → вниз
    ['0.005', 1], // ровно половина → от нуля
    ['-0.005', -1], // ровно половина → от нуля
    ['2.675', 268], // 267.5 минорной → 268, float дал бы 267
  ])('%s → %i минорных', (input, minor) => {
    expect(evalExpr(input)).toEqual({ ok: true, minor })
  })
})

describe('evalExpr — пробелы между токенами игнорируются', () => {
  it('"  1500 / 4 + 200  " → 57500', () => {
    expect(evalExpr('  1500 / 4 + 200  ')).toEqual({ ok: true, minor: 57500 })
  })
})

describe('evalExpr — граница безопасного целого', () => {
  it('90000000000000 → minor 9000000000000000 (в пределах MAX_SAFE_INTEGER)', () => {
    expect(evalExpr('90000000000000')).toEqual({ ok: true, minor: 9000000000000000 })
  })
})

describe('evalExpr — некорректный ввод: ok:false без исключений', () => {
  it.each([
    [''], // пустая строка
    ['   '], // только пробелы
    ['1+'], // висящий оператор
    ['1+2)'], // лишняя закрывающая скобка
    ['(1+2'], // незакрытая скобка
    ['1 2'], // два числа подряд
    ['1..2'], // двойной разделитель
    ['1,5.5'], // смешанные разделители
    ['.5'], // разделитель без целой части
    ['1.'], // хвостовой разделитель
    ['+1'], // унарный плюс не поддержан
    ['abc'], // мусор
    ['1,000,5'], // второй разделитель в литерале
    ['1/0'], // деление на ноль
    ['5/(2-2)'], // деление на вычисленный ноль
    ['99999999999999999'], // результат за Number.MAX_SAFE_INTEGER
  ])('"%s" → ok:false', (input) => {
    expect(evalExpr(input)).toEqual({ ok: false })
  })
})
